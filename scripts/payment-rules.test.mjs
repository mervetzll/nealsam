import assert from 'node:assert/strict';
import {createHmac} from 'node:crypto';
import {isPaymentPlan,moneyString,parseBuyer,validateCheckout} from '../src/lib/paymentRules.ts';
import {verifyIyzicoSignature,safePaymentPage,paymentConfig} from '../src/lib/paymentServer.ts';
process.env.IYZICO_SECRET_KEY='test-secret';
const attempt={id:'order-id',user_id:'user-id',plan:'plus',price:49,iyzico_token:'test-token',status:'initialized'};
const result={status:'success',paymentStatus:'SUCCESS',paymentId:'123',fraudStatus:1,currency:'TRY',basketId:'nealsam-order-id',conversationId:'order-id',paidPrice:'49.00',price:49,token:'test-token'};
assert.equal(validateCheckout(result,attempt),'approved');
for(const field of ['token','conversationId','basketId','currency']) assert.notEqual(validateCheckout({...result,[field]:'wrong'},attempt),'approved');
for(const field of ['price','paidPrice']) assert.notEqual(validateCheckout({...result,[field]:1},attempt),'approved');
assert.notEqual(validateCheckout({...result,fraudStatus:0},attempt),'approved');
assert.notEqual(validateCheckout({...result,fraudStatus:-1},attempt),'approved');
assert.notEqual(validateCheckout({...result,paymentStatus:'FAILURE'},attempt),'approved');
assert.notEqual(validateCheckout(result,{...attempt,price:1}),'approved');
assert.equal(isPaymentPlan('toString'),false);
assert.equal(isPaymentPlan('__proto__'),false);
assert.equal(moneyString('49.00'),'49');
assert.equal(moneyString('49.10'),'49.1');
assert.equal(moneyString('49x'),'');
const signature=createHmac('sha256','test-secret').update('SUCCESS:123:TRY:nealsam-order-id:order-id:49:49:test-token').digest('hex');
assert.equal(verifyIyzicoSignature({...result,signature}),true);
assert.equal(verifyIyzicoSignature({...result,signature,price:1}),false);
assert.equal(verifyIyzicoSignature({...result,signature:'wrong'}),false);
const initSignature=createHmac('sha256','test-secret').update('order-id:test-token').digest('hex');
assert.equal(verifyIyzicoSignature({conversationId:'order-id',token:'test-token',signature:initSignature},true),true);
assert.equal(safePaymentPage('https://sandbox-cpp.iyzipay.com/?token=test'),true);
assert.equal(safePaymentPage('https://sandbox-cpp.iyzipay.com.evil.example'),false);
assert.equal(safePaymentPage('http://cpp.iyzipay.com'),false);
assert.equal(parseBuyer({}),null);
assert.equal(parseBuyer({name:'Test',surname:'Kullanıcı',phone:'05320000000',identityNumber:'11111111111',address:'Yalnızca test adresi',city:'İstanbul'}).phone,'+905320000000');
process.env.IYZICO_API_KEY='test';
process.env.IYZICO_BASE_URL='https://api.iyzipay.com';
delete process.env.PAYMENTS_ENABLED;
assert.equal(paymentConfig().ready,false);
process.env.IYZICO_BASE_URL='https://sandbox-api.iyzipay.com';
delete process.env.IYZICO_TEST_EMAILS;
assert.equal(paymentConfig().ready,false);
process.env.IYZICO_TEST_EMAILS='owner@example.invalid';
assert.equal(paymentConfig().ready,true);
console.log('Ödeme imzası, tutar, para birimi, test erişimi ve alıcı doğrulama kontrolleri geçti.');
